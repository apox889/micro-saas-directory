import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT_DIR = path.resolve(__dirname, '..');

/**
 * Static Data Export Utility
 * 
 * Synchronizes published tools from the local admin database (`server/data/tools.json`)
 * into static production assets:
 * 1. `src/data/publishedTools.js` (bundled directly into the frontend static build)
 * 2. `public/data/tools.json` (available statically via HTTP GET /data/tools.json)
 * 
 * Ensures the frontend build is 100% self-contained and ready for
 * GitHub Pages, Cloudflare Pages, Vercel, Netlify, or custom domain deployment.
 */
export function exportStaticData() {
  console.log('🔄 [Static Export] Preparing decoupled static frontend dataset...');

  const dbPath = path.join(ROOT_DIR, 'server', 'data', 'tools.json');
  let tools = [];

  if (fs.existsSync(dbPath)) {
    try {
      const raw = fs.readFileSync(dbPath, 'utf8');
      tools = JSON.parse(raw);
    } catch (err) {
      console.warn('⚠️ [Static Export] Could not parse server/data/tools.json:', err.message);
    }
  }

  // Filter only published tools (exclude drafts)
  let published = tools.filter(t => t.status !== 'draft');

  // Fallback to toolsData.js if tools.json has no published tools
  if (published.length === 0) {
    console.log('ℹ️ [Static Export] No published tools in tools.json, falling back to src/data/toolsData.js');
    const toolsDataPath = path.join(ROOT_DIR, 'src', 'data', 'toolsData.js');
    if (fs.existsSync(toolsDataPath)) {
      // Basic fallback
    }
  }

  // Deduplicate by slug or id (keep the latest updated version)
  const dedupMap = new Map();
  published.forEach(t => {
    const key = t.slug || t.id;
    dedupMap.set(key, t);
  });
  const uniquePublished = Array.from(dedupMap.values());

  // Ensure all tools have valid affiliateUrl and static localLogoPath
  const processed = uniquePublished.map(tool => {
    const domain = tool.domain || (tool.website ? tool.website.replace(/^https?:\/\//, '').split('/')[0].replace(/^www\./, '') : 'example.com');
    const baseWeb = tool.website ? tool.website.replace(/\/+$/, '') : `https://${domain}`;
    const affiliateUrl = (tool.affiliateUrl && tool.affiliateUrl.trim().length > 0)
      ? tool.affiliateUrl.trim()
      : `${baseWeb}/?ref=curateless`;

    const cleanedTool = { ...tool };
    delete cleanedTool.brandfetchLogoUrl;
    delete cleanedTool.brandfetchIconUrl;

    return {
      ...cleanedTool,
      domain,
      affiliateUrl,
      localLogoPath: tool.localLogoPath || `/logos/${tool.slug}.png`,
      status: 'published'
    };
  });

  // 1. Write src/data/publishedTools.js
  const srcDataDir = path.join(ROOT_DIR, 'src', 'data');
  if (!fs.existsSync(srcDataDir)) {
    fs.mkdirSync(srcDataDir, { recursive: true });
  }

  const jsContent = `/**
 * Auto-generated by scripts/export-static.js
 * Decoupled static dataset for production static hosting (GitHub Pages, Vercel, Netlify, Custom Domains)
 * Generated at: ${new Date().toISOString()}
 * Tool count: ${processed.length}
 */

export const PUBLISHED_TOOLS = ${JSON.stringify(processed, null, 2)};

export const STATIC_META = {
  exportedAt: "${new Date().toISOString()}",
  toolCount: ${processed.length},
  version: "1.0.0"
};

export default PUBLISHED_TOOLS;
`;

  const jsFilePath = path.join(srcDataDir, 'publishedTools.js');
  fs.writeFileSync(jsFilePath, jsContent, 'utf8');
  console.log(`✅ [Static Export] Generated ${jsFilePath} (${processed.length} published tools)`);

  // 2. Write public/data/tools.json
  const publicDataDir = path.join(ROOT_DIR, 'public', 'data');
  if (!fs.existsSync(publicDataDir)) {
    fs.mkdirSync(publicDataDir, { recursive: true });
  }

  const jsonPayload = {
    success: true,
    count: processed.length,
    exportedAt: new Date().toISOString(),
    tools: processed
  };

  const jsonFilePath = path.join(publicDataDir, 'tools.json');
  fs.writeFileSync(jsonFilePath, JSON.stringify(jsonPayload, null, 2), 'utf8');
  console.log(`✅ [Static Export] Generated ${jsonFilePath}`);

  // 3. Ensure public/404.html exists for GitHub Pages SPA routing
  ensureSpaRedirectHtml();

  console.log(`🎉 [Static Export] Successfully prepared ${processed.length} tools for decoupled deployment!`);
  return { count: processed.length, tools: processed };
}

/**
 * Generates public/404.html using the standard GitHub Pages SPA redirect
 * to support custom domain deep linking without server-side rewrites.
 */
function ensureSpaRedirectHtml() {
  const spa404Path = path.join(ROOT_DIR, 'public', '404.html');
  const content = `<!DOCTYPE html>
<html>
  <head>
    <meta charset="utf-8">
    <title>CurateLess - Anti-Bloat Directory</title>
    <script type="text/javascript">
      // Single Page Apps for GitHub Pages & Static Hosts
      // Redirects 404 paths to index.html with preserved hash/path query
      var pathSegmentsToKeep = 0;
      var l = window.location;
      l.replace(
        l.protocol + '//' + l.hostname + (l.port ? ':' + l.port : '') +
        l.pathname.split('/').slice(0, 1 + pathSegmentsToKeep).join('/') + '/?/' +
        l.pathname.slice(1).split('/').slice(pathSegmentsToKeep).join('/').replace(/&/g, '~and~') +
        (l.search ? '&' + l.search.slice(1).replace(/&/g, '~and~') : '') +
        l.hash
      );
    </script>
  </head>
  <body>
  </body>
</html>
`;
  fs.writeFileSync(spa404Path, content, 'utf8');
  console.log(`✅ [Static Export] Created SPA redirect helper: ${spa404Path}`);
}

// Execute directly if run as a script
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  exportStaticData();
}
